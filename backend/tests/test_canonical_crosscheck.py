"""
backend/tests/test_canonical_crosscheck.py
Cross-check test: verifies deterministic canonical serialization across floats,
nested structures, and native unicode, ensuring signatures generated by probes
are identically validated by the server and Merkle verifiers.
"""

import json
from cryptography.hazmat.primitives.asymmetric import ed25519
from utils.canonical import canonical_json_dumps
from probe.client import canonical_json_dumps as probe_canonical_json


def test_canonical_json_identical_implementation():
    """Verify that backend and probe import/use the identical canonical serializer."""
    payload = {
        "domain": "विकिपीडिया.org",
        "asn": 55836,
        "score": 0.985,
        "nested": {
            "zebra": 1,
            "alpha": True,
            "beta": [3, 2, 1],
            "unicode_text": "इंटरनेट सेंसरशिप",
        },
        "flags": [None, False, True],
    }

    server_bytes = canonical_json_dumps(payload)
    probe_bytes = probe_canonical_json(payload)

    # Must produce exact byte-for-byte equality
    assert server_bytes == probe_bytes

    # Keys must be sorted deterministically
    decoded = server_bytes.decode("utf-8")
    expected_start = '{"asn":55836,"domain":"विकिपीडिया.org","flags":[null,false,true],"nested":{"alpha":true,"beta":[3,2,1],"unicode_text":"इंटरनेट सेंसरशिप","zebra":1},"score":0.985}'
    assert decoded == expected_start


def test_signature_cross_verification_floats_unicode_nested():
    """Verify probe signs complex canonical payload and server verifies exact bytes."""
    private_key = ed25519.Ed25519PrivateKey.generate()
    public_key = private_key.public_key()

    complex_payload = {
        "domain": "thepiratebay.org",
        "asn": 55836,
        "measured_at": 1711234567.89,
        "anomaly": True,
        "signals": {
            "dns_tampering": True,
            "http_block": False,
            "location": "नई दिल्ली",
            "rates": [1.5, 2.75, 3.125],
        },
        "nonce": "test-uuid-crosscheck-123",
        "timestamp": 1711234567,
        "software_version": "0.1.0",
    }

    # Probe serializes and signs
    probe_bytes = probe_canonical_json(complex_payload)
    sig = private_key.sign(probe_bytes)

    # Server serializes and verifies
    server_bytes = canonical_json_dumps(complex_payload)
    public_key.verify(sig, server_bytes)
